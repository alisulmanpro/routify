import { useEffect, useState } from 'react';
import { get } from '../lib/api';
import type { ReportRow } from '../lib/types';
import { dateShort } from '../lib/format';
import Pagination from '../components/Pagination';
import { useToast } from '../components/Toast';
import { API_URL, getAccessToken } from '../lib/api';

export default function Reports() {
  const toast = useToast();
  const [rows, setRows] = useState<ReportRow[]>([]);
  const [page, setPage] = useState(1);
  const [pages, setPages] = useState(1);
  const [search, setSearch] = useState('');
  const [loading, setLoading] = useState(true);

  const load = () => {
    setLoading(true);
    get<ReportRow[]>('/admin/reports', { page, limit: 25, search: search || undefined })
      .then((r) => { setRows(r.data); setPages(r.meta?.pages || 1); })
      .catch((e) => toast('error', e.message))
      .finally(() => setLoading(false));
  };
  useEffect(load, [page]); // eslint-disable-line react-hooks/exhaustive-deps

  const openReport = async (path: string) => {
    // downloadUrl is API-relative and HMAC-signed; fetch with the current bearer token and open as a blob.
    try {
      const res = await fetch(`${API_URL}${path}`, { headers: { Authorization: `Bearer ${getAccessToken() || ''}` } });
      if (!res.ok) throw new Error('Could not open report');
      const blob = await res.blob();
      window.open(URL.createObjectURL(blob), '_blank');
    } catch (e) {
      toast('error', e instanceof Error ? e.message : 'Could not open report');
    }
  };

  return (
    <section className="module-view">
      <div className="module-heading"><div><p className="eyebrow">Admin workspace</p><h1>Reports</h1><p className="heading-copy">Daily delivery reports generated by riders.</p></div></div>

      <form className="filter-row" onSubmit={(e) => { e.preventDefault(); setPage(1); load(); }}>
        <input className="input table-search" placeholder="Search rider or organization…" value={search} onChange={(e) => setSearch(e.target.value)} />
        <button className="text-button" type="submit">Search</button>
      </form>

      <div className="panel module-table">
        {loading ? <div className="loading-state">Loading…</div> : rows.length === 0 ? <div className="module-empty-copy">No reports have been generated yet.</div> : (
          <div className="table-wrap">
            <table>
              <thead><tr><th>Date</th><th>Rider</th><th>Total</th><th>Delivered / Failed</th><th></th></tr></thead>
              <tbody>
                {rows.map((r) => (
                  <tr key={r.id}>
                    <td>{dateShort(r.date)}</td><td>{r.riderName || '—'}</td>
                    <td>{r.summary.total}</td><td>{r.summary.delivered} / {r.summary.failed}</td>
                    <td><button className="text-button" onClick={() => openReport(r.downloadUrl)}>Download PDF</button></td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
        <Pagination page={page} pages={pages} onChange={setPage} />
      </div>
    </section>
  );
}
